/**
 * Алгоритм тасования Фишера-Йетса
 */
function shuffleArray(array) {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Подготовка пула заданий по выбранной теме
 * - Для темы "Дроби":
 *   1) 10 вводных заданий: преобразование деления в дробь (строго идут первыми, 1..10)
 *   2) 10 вводных заданий: знаменатель и числитель (строго идут вторыми, 11..20)
 *   3) 30 заданий: сложение и вычитание обыкновенных дробей (перемешиваются)
 * - Варианты ответов для каждого задания перемешиваются случайным образом
 */
function prepareTasksForSession(topic = 'all', count = 10) {
  let selectedTasks = [];

  if (topic === 'fractions') {
    // 10 заданий: деление в обыкновенную дробь (строго 1..10)
    const divisionTasks = RAW_TASKS.filter(t => t.topic === 'fractions' && t.isDivisionIntro)
      .sort((a, b) => (a.divisionOrder || 0) - (b.divisionOrder || 0));

    // 10 заданий: знаменатель и числитель (строго вторые, 11..20)
    const partsTasks = RAW_TASKS.filter(t => t.topic === 'fractions' && t.isPartsIntro)
      .sort((a, b) => (a.partsOrder || 0) - (b.partsOrder || 0));

    // 30 заданий: сложение и вычитание дробей
    const calcTasks = RAW_TASKS.filter(t => t.topic === 'fractions' && !t.isDivisionIntro && !t.isPartsIntro);

    const orderedIntroTasks = [...divisionTasks, ...partsTasks]; // 20 заданий (10 делений + 10 числитель/знаменатель)

    if (count <= orderedIntroTasks.length) {
      selectedTasks = orderedIntroTasks.slice(0, count);
    } else {
      const remainingCount = count - orderedIntroTasks.length;
      const shuffledCalc = shuffleArray(calcTasks);
      selectedTasks = [...orderedIntroTasks, ...shuffledCalc.slice(0, remainingCount)];
    }
  } else if (topic !== 'all') {
    const filtered = RAW_TASKS.filter(t => t.topic === topic);
    const shuffledTasks = shuffleArray(filtered);
    selectedTasks = shuffledTasks.slice(0, Math.min(count, shuffledTasks.length));
  } else {
    // 'all'
    const shuffledTasks = shuffleArray(RAW_TASKS);
    selectedTasks = shuffledTasks.slice(0, Math.min(count, shuffledTasks.length));
  }

  // Для каждого задания перемешиваем варианты ответов
  return selectedTasks.map(task => {
    const shuffledOptions = shuffleArray(task.options);
    return {
      ...task,
      shuffledOptions,
      correctIndex: shuffledOptions.indexOf(task.correct)
    };
  });
}

